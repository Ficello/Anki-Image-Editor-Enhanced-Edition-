def get_current_language_code() -> str:
    """Retrieve active Anki locale and normalize to language key."""
    lang_code = "en"
    try:
        if callable(current_lang):
            lang_code = current_lang()
        elif mw and hasattr(mw, "pm") and mw.pm:
            lang_code = mw.pm.meta.get("lang", "en")
    except Exception:
        lang_code = "en"

    if not lang_code:
        return "en"

    # Exact match (e.g. 'pt_BR', 'zh_CN', 'zh_TW', 'nb_NO')
    lang_code = lang_code.replace("-", "_")
    if lang_code in STRINGS:
        return lang_code

    # Match primary prefix (e.g. 'fr_FR' -> 'fr', 'de_DE' -> 'de', 'es_ES' -> 'es')
    base_code = lang_code.split("_")[0].lower()
    if base_code in STRINGS:
        return base_code
    
    # Check if prefix matches any key
    for k in STRINGS:
        if k.lower().startswith(base_code):
            return k

    return "en"


def tr(key: str, default: Optional[str] = None, **kwargs) -> str:
    """
    Translate a string key using the active language with English fallback.
    Supports formatting parameters via kwargs.
    """
    lang = get_current_language_code()
    
    # Try active language
    text = STRINGS.get(lang, {}).get(key)
    
    # Fallback to English
    if text is None:
        text = STRINGS.get("en", {}).get(key)
        
    # Fallback to provided default or key itself
    if text is None:
        text = default if default is not None else key

    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
            
    return text


def get_all_translations() -> Dict[str, str]:
    """Returns the complete translation dictionary for the active language."""
    lang = get_current_language_code()
    result = dict(STRINGS.get("en", {}))
    if lang in STRINGS and lang != "en":
        result.update(STRINGS[lang])
    return result
